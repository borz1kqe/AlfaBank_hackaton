    def __init__(self, base_dir: str = ".") -> None:
        self.base_dir = Path(base_dir)
        self.raw_dir = self.base_dir / "data" / "raw"
        self.analytics_dir = self.base_dir / "data" / "bank_analytics"
        self.raw_dir.mkdir(parents=True, exist_ok=True)
        self.analytics_dir.mkdir(parents=True, exist_ok=True)

    def generate_all(self, overwrite: bool = False) -> Dict[str, Path]:
        uid_path = self.raw_dir / "df_Uid_data_hack.csv"
        fid_path = self.raw_dir / "df_Fid_Uid_link_hack.csv"
        news_path = self.raw_dir / "news_feed.json"
        analytics_path = self.analytics_dir / "bank_research.json"

        if overwrite or not uid_path.exists():
            self._generate_uid_csv(uid_path)
        if overwrite or not fid_path.exists():
            self._generate_fid_payments_csv(fid_path)
        if overwrite or not analytics_path.exists():
            self._generate_bank_analytics(analytics_path)
        if overwrite or not news_path.exists():
            self._generate_news_feed(news_path)

        return {
            "uid_csv": uid_path,
            "fid_csv": fid_path,
            "news_json": news_path,
            "analytics_json": analytics_path,
        }

